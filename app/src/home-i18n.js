export function getUiLocale() {
  return typeof document !== "undefined" && document.documentElement.lang === "en" ? "en" : "de";
}

export function translateText(text, locale = getUiLocale()) {
  if (locale !== "en" || typeof text !== "string") return text;
  const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/u);
  if (!match) return text;
  const key = match[2].replace(/\s+/gu, " ").trim();
  if (!key) return text;
  let translated = TRANSLATIONS[key];
  if (translated === undefined) {
    translated = key;
    for (const [pattern, replacement] of RULES) translated = translated.replace(pattern, replacement);
    if (translated === key) return text;
  }
  return match[1] + translated + match[3];
}

export function localizeTree(node, locale = getUiLocale()) {
  if (locale !== "en") return node;
  if (typeof node === "string") return translateText(node, locale);
  if (Array.isArray(node)) return node.map((child) => localizeTree(child, locale));
  if (!isValidElement(node)) return node;
  if (typeof node.type !== "string" && node.type !== Fragment) return node;
  const overrides = {};
  for (const prop of ["title", "aria-label", "placeholder", "alt"]) {
    if (typeof node.props[prop] === "string") overrides[prop] = translateText(node.props[prop], locale);
  }
  if (node.props.children !== undefined) overrides.children = Children.map(node.props.children, (child) => localizeTree(child, locale));
  return cloneElement(node, overrides);
}
